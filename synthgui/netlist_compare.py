"""Write a testbench that runs legend64_soc's RTL and its mapped netlist side by side and compares
every register the netlist names after an RTL signal, on each clock:

    netlist_compare.py <mapped netlist.v> <output directory> [boot image.hex]

It writes <dir>/soc_map_ren.v (the netlist with its module renamed legend64_soc_map) and
<dir>/tb.sv; compare.sh builds and runs them. The first cycle reported is where the netlist's
logic first departs from the RTL, and the register names say where to look.
"""
import os, re, sys

net, out = sys.argv[1], sys.argv[2]
boot = os.path.abspath(sys.argv[3] if len(sys.argv) > 3 else 'build/fpga/boot_sim.hex')
s = open(net).read()
open(os.path.join(out, 'soc_map_ren.v'), 'w').write(re.sub(r'^module legend64_soc\b', 'module legend64_soc_map', s, flags=re.M))
checks = []
for kind, par, name, body in re.findall(r'\b(FD[RSCP]E)\s+#\(([^;]*?)\)\s+(\S+)\s+\((.*?)\);', s, re.S):
    clk = re.search(r'\.C\((.*?)\)\s*,', body, re.S).group(1).strip()
    q = re.search(r'\.Q\((.*?)\)\s*\)?\s*$', body, re.S).group(1).strip()
    if clk != '\\u_boot.clk':
        continue                                  # the system clock only: one sample point
    rtl = re.sub(r'__(\d+)', r'[\1]', q.lstrip('\\'))   # arr__3[5] is arr[3][5]
    if rtl.endswith('_n') or 'wire_' in rtl:
        continue                                  # the mapper's own registers
    checks.append('    if (u_ref.%s !== u_map.%s ) bad("%s", u_ref.%s, u_map.%s );' % (rtl, q, rtl, rtl, q))

ports = '''.clk, .rst, .ddr_ready(1'b1), .ddr_soft(1'b0),
      .dcsr_req(), .dcsr_we(), .dcsr_addr(), .dcsr_wdata(), .dcsr_ack(1'b0), .dcsr_rdata(32'h0),
      .mem_req(%s_req), .mem_we(%s_we), .mem_addr(%s_addr), .mem_wdata(%s_wd), .mem_ack(%s_ack), .mem_rdata(%s_rd),
      .uart_tx(%s_tx), .uart_rx(1'b1), .led(%s_led), .dip(8'h00), .btn(5'h0),
      .mac_clk, .mac_rst(rst), .mac_tx_clk(mac_clk), .mac_tx_rst(rst), .tx_pcs_frames(16'h0),
      .rx_tdata(8'h0), .rx_tvalid(1'b0), .rx_tlast(1'b0), .rx_tuser(1'b0),
      .tx_tdata(), .tx_tvalid(), .tx_tlast(), .tx_tready(1'b1), .pcs_status(16'h0c03),
      .fl_addr(), .fl_dq_i(16'hffff), .fl_dq_o(), .fl_dq_t(), .fl_ce_n(), .fl_oe_n(), .fl_we_n(), .fl_adv_n(), .reconfig()'''
open(os.path.join(out, 'tb.sv'), 'w').write('''`timescale 1ns / 1ps
// Generated by synthgui/netlist_compare.py: the SoC's RTL and its mapped netlist side by side.
module memmodel (input logic clk, input logic req, we, input logic [23:0] addr, input logic [511:0] wdata,
                 output logic ack, output logic [511:0] rdata);
  logic [511:0] lines[int];
  int delay = 0;
  initial ack = 0;
  always @(posedge clk) begin
    if (req && !ack) begin
      delay <= delay + 1;
      if (delay == 6) begin
        if (we) lines[int'(addr)] = wdata;
        else rdata <= lines.exists(int'(addr)) ? lines[int'(addr)] : '0;
        ack <= 1;
      end
    end else begin
      delay <= 0;
      if (!req) ack <= 0;
    end
  end
endmodule

module tb;
  logic clk = 0, mac_clk = 0, rst = 1;
  always #10 clk = ~clk;
  always #4 mac_clk = ~mac_clk;
  wire        r_req, r_we, r_ack, m_req, m_we, m_ack, r_tx, m_tx;
  wire [23:0] r_addr, m_addr;
  wire [511:0] r_wd, r_rd, m_wd, m_rd;
  wire [7:0]  r_led, m_led;
  legend64_soc #(.CLK_HZ(50_000_000), .BAUD(3_000_000), .BOOT_HEX("%s")) u_ref (
      %s);
  memmodel u_rmem (.clk, .req(r_req), .we(r_we), .addr(r_addr), .wdata(r_wd), .ack(r_ack), .rdata(r_rd));
  legend64_soc_map u_map (
      %s);
  memmodel u_mmem (.clk, .req(m_req), .we(m_we), .addr(m_addr), .wdata(m_wd), .ack(m_ack), .rdata(m_rd));
  longint cycles = 0, max_cycles = 300000;
  int nbad = 0, badcycles = 0;
  function automatic void bad(input string n, input logic a, input logic b);
    nbad++;
    if (nbad <= 60) $display("cycle %%0d: %%s RTL %%b netlist %%b", cycles, n, a, b);
  endfunction
  initial begin
    void'($value$plusargs("cycles=%%d", max_cycles));
    repeat (20) @(posedge clk); rst = 0;
  end
`ifdef BHT_ZERO
  // for a mapper that leaves the branch history table's initial value out of the netlist
  initial begin #1; for (int i = 0; i < $size(u_ref.u_core.bht); i++) u_ref.u_core.bht[i] = 2'b00; end
`endif
  always @(negedge clk) if (!rst) begin
    cycles <= cycles + 1;
    nbad = 0;
%s
    if (nbad != 0) begin
      badcycles++;
      $display("cycle %%0d: %%0d registers differ; led %%h/%%h (RTL/netlist)", cycles, nbad, r_led, m_led);
      if (badcycles == 2) $finish;
    end
    if (cycles %% 50000 == 0) $display("cycle %%0d: in step, led %%h", cycles, r_led);
    if (cycles == max_cycles) begin $display("IN STEP for %%0d cycles: %%0d registers compared, led %%h/%%h", cycles, %d, r_led, m_led); $finish; end
  end
endmodule
''' % (boot, ports % (('r',) * 8), ports % (('m',) * 8), '\n'.join(checks), len(checks)))
print('%d registers compared' % len(checks))
